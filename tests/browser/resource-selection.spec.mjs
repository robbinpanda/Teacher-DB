test.use({ extraHTTPHeaders: { 'oai-authenticated-user-id': 'resource-selection-browser' } });
const owner = 'resource-selection-browser';
const database = () => new Database(path.join(process.env.JIANTI_E2E_DATA_DIR, 'teacher-question-bank.sqlite3'));
function seed(db, count = 3, name = '交互验证原卷') {
  const stamp = new Date().toISOString(), doc = crypto.randomUUID(), ids = [];
  db.prepare("INSERT INTO documents (id,owner_id,name,mime_type,status,subject,grade,created_at,updated_at) VALUES (?,?,?,'application/pdf','complete','数学','九年级',?,?)").run(doc, owner, name, stamp, stamp);
  for (let i = 0; i < count; i++) {
    const id = crypto.randomUUID(); ids.push(id);
    db.prepare("INSERT INTO questions (id,document_id,number,type,stem,answer,analysis,status,needs_human_review,page_number,bbox_json,created_at,updated_at) VALUES (?,?,?,'fill',?,'2','代入公式求解','approved',0,1,'{}',?,?)").run(id, doc, String(i + 1), `交互题目 ${i + 1}：求解 $x^2=4$。\n已知条件如下，请说明理由。\n$$\\frac{x^2+1}{x-1}=5$$\n请保留完整的计算过程。`, stamp, stamp);
  }
  return { doc, ids };
}

