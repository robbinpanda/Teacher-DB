test('试卷库：两类与混选、移动、失败重试、安全删除、长名称、空白草稿及空列表', async ({ page, request }) => {
  test.setTimeout(90000);
  const db = database();
  const longTitle = '长名称验证——' + '九年级数学期末综合能力测试'.repeat(8);
  const a = seed(db, 2, longTitle); seed(db, 1, '第二份批量原卷');
  const stamp = new Date().toISOString(), p1 = crypto.randomUUID(), p2 = crypto.randomUUID();
  for (const [id, title] of [[p1, '批量作品一'], [p2, '空白作品二']]) db.prepare("INSERT INTO papers (id,owner_id,title,settings_json,created_at,updated_at) VALUES (?,?,?,'{}',?,?)").run(id, owner, title, stamp, stamp);
  db.prepare('INSERT INTO paper_items (paper_id,question_id,position,score) VALUES (?,?,?,?)').run(p1, a.ids[0], 0, 5);
  const folderResponse = await request.post('/api/paper-folders', { data: { name: '批量目标文件夹' } });
  expect(folderResponse.ok()).toBe(true);
  const folder = (await folderResponse.json()).folder;
  await page.goto('/papers');
  const bulk = page.getByRole('region', { name: '试卷批量操作' });
  const checkbox = title => page.getByRole('checkbox', { name: `选择试卷 ${title}`, exact: true });
  await checkbox(longTitle).check();
  await checkbox('第二份批量原卷').check();
  await expect(bulk).toContainText('已选 2 份');
  await page.getByRole('tab', { name: /组卷作品/ }).click();
  await expect(bulk).toHaveCount(0);
  await checkbox('批量作品一').check(); await checkbox('空白作品二').check();
  await expect(bulk).toContainText('已选 2 份');
  await expect(page.locator('tr').filter({ hasText: '空白作品二' })).toContainText('空白草稿');
  await page.getByRole('tab', { name: /全部试卷/ }).click();
  await page.getByLabel('全选当前筛选结果').check();
  await expect(page.locator('.asset-table tbody input:checked')).toHaveCount(await page.locator('.asset-table tbody tr').count());
  await page.getByLabel('全选当前筛选结果').uncheck();
  await expect(bulk).toHaveCount(0);
  await checkbox(longTitle).check(); await checkbox('批量作品一').check();
  await expect(page.getByLabel('全选当前筛选结果')).toHaveJSProperty('indeterminate', true);
  for (const width of [1440, 1920]) {
    await page.setViewportSize({ width, height: 1000 });
    await page.screenshot({ path: `tmp/paper-selection-${width}.png`, fullPage: true });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    const title = page.locator('.asset-title').filter({ hasText: longTitle });
    await expect(title).toHaveAttribute('title', longTitle);
    expect(await title.evaluate(el => el.scrollWidth > el.clientWidth && getComputedStyle(el).textOverflow === 'ellipsis')).toBe(true);
  }
  await page.getByLabel('批量移动试卷').selectOption(folder.id);
  await expect(page.locator('.resource-operation-notice')).toContainText('已移动 2 份');
  expect(db.prepare('SELECT paper_folder_id FROM documents WHERE id=?').pluck().get(a.doc)).toBe(folder.id);
  expect(db.prepare('SELECT folder_id FROM papers WHERE id=?').pluck().get(p1)).toBe(folder.id);
  await expect(bulk).toHaveCount(0);
  // Real SQLite rejection, no mocked API responses; the failed record remains retryable.
  await checkbox('第二份批量原卷').check(); await checkbox('空白作品二').check();
  db.exec(`CREATE TRIGGER reject_test_move BEFORE UPDATE OF folder_id ON papers WHEN OLD.id='${p2}' BEGIN SELECT RAISE(ABORT, 'test folder locked'); END`);
  await page.getByLabel('批量移动试卷').selectOption(folder.id);
  await expect(page.locator('.resource-operation-notice')).toContainText('已移动 1 份，1 份失败');
  await expect(bulk).toContainText('已选 1 份');
  db.exec('DROP TRIGGER reject_test_move');
  await page.getByLabel('批量移动试卷').selectOption(folder.id);
  await expect(page.locator('.resource-operation-notice')).toHaveText('已移动 1 份');
  await expect(bulk).toHaveCount(0);
  db.prepare('INSERT INTO paper_items (paper_id,question_id,position,score) VALUES (?,?,0,5)').run(p2, a.ids[1]);
  await checkbox(longTitle).check(); await checkbox('批量作品一').check();
  page.once('dialog', dialog => dialog.dismiss());
  await bulk.getByRole('button', { name: '批量删除', exact: true }).click();
  expect(db.prepare('SELECT COUNT(*) FROM papers WHERE id=?').pluck().get(p1)).toBe(1);
  page.once('dialog', dialog => { expect(dialog.message()).toContain('保留题目'); return dialog.accept(); });
  await bulk.getByRole('button', { name: '批量删除', exact: true }).click();
  await expect(page.locator('.resource-operation-notice')).toContainText('已删除 2 份');
  expect(db.prepare('SELECT COUNT(*) FROM questions WHERE document_id=?').pluck().get(a.doc)).toBe(2);
  expect(db.prepare('SELECT source_removed_at FROM documents WHERE id=?').pluck().get(a.doc)).toBeTruthy();
  expect(db.prepare('SELECT COUNT(*) FROM paper_items WHERE paper_id=? AND question_id=?').pluck().get(p2, a.ids[1])).toBe(1);
  await checkbox(longTitle).check();
  await expect(bulk.getByRole('button', { name: '批量删除', exact: true })).toBeDisabled();
  await bulk.getByRole('button', { name: '取消选择' }).click();
  await checkbox('第二份批量原卷').check();
  await page.getByRole('button', { name: '文件夹管理' }).click();
  await page.locator('.paper-folder-tree').getByRole('button', { name: /批量目标文件夹/ }).click();
  await expect(bulk).toHaveCount(0);
  await expect(page.locator('.asset-table tbody tr')).toHaveCount(3);
  await page.getByLabel('空白作品二 操作').click();
  page.once('dialog', dialog => dialog.accept());
  await page.getByRole('button', { name: '删除组卷作品', exact: true }).click();
  await expect(page.locator('.asset-table tbody tr')).toHaveCount(2);
  expect(db.prepare('SELECT COUNT(*) FROM questions WHERE document_id=?').pluck().get(a.doc)).toBe(2);
  await page.getByLabel('搜索当前范围试卷').fill('没有这份试卷');
  await expect(page.getByRole('heading', { name: '没有匹配的试卷' })).toBeVisible();
  await expect(page.getByLabel('全选当前筛选结果')).toBeDisabled();
  db.close();
});
